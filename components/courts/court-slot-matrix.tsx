/* ----------------------------- lock countdown ---------------------------- */

function useCountdown(expiresAt?: string | null) {
  // `now` stays null until the first interval tick. That keeps state updates
  // inside the callback (never the effect body) and, because the server and
  // the first client render both produce no countdown, avoids a hydration
  // mismatch on this statically prerendered page.
  const [now, setNow] = React.useState<number | null>(null)

  React.useEffect(() => {
    if (!expiresAt) return
    const id = setInterval(() => setNow(Date.now()), 1000)
    return () => clearInterval(id)
  }, [expiresAt])

  if (!expiresAt || now === null) return null
  const total = Math.floor(Math.max(0, new Date(expiresAt).getTime() - now) / 1000)
  return `${Math.floor(total / 60)}:${String(total % 60).padStart(2, '0')}`
}

/* -------------------------------- slot cell ------------------------------ */

const STATE_LABEL: Record<SlotState, string> = {
  available: 'Disponible',
  occupied: 'Réservé',
  locked_buffer: 'En cours de réservation',
  past: 'Passé',
}

function SlotCell({
  court,
  slot,
  isSelected,
  onSelect,
  animate,
  selectedDate,
}: {
  court: MatrixCourt
  slot: MatrixSlot
  isSelected: boolean
  onSelect: () => void
  animate: boolean
  selectedDate: string
}) {
  const countdown = useCountdown(
    slot.state === 'locked_buffer' ? slot.lockExpiresAt : null
  )
  const isAvailable = slot.state === 'available'
  const price = slotPrice(court, slot, selectedDate)
  const peak = slotIsPeak(court, slot, selectedDate)

  const tooltip =
    slot.state === 'available'
      ? `${formatTND(price)} · ${peak ? 'Pointe (éclairage de nuit)' : 'Heures creuses'} · ${slotMinutes(court.sport)} min + ${BUFFER_MIN} min de battement`
      : slot.state === 'occupied'
        ? 'Déjà réservé'
        : slot.state === 'locked_buffer'
          ? countdown
            ? `Retenu par un autre joueur — ${countdown} restantes`
            : 'Retenu par un autre joueur'
          : 'Ce créneau est déjà passé'

  const cell = (
    <motion.button
      type="button"
      layout
      variants={
        animate
          ? {
              hidden: { opacity: 0, y: 8 },
              show: { opacity: 1, y: 0 },
            }
          : undefined
      }
      whileHover={animate && isAvailable ? { y: -2 } : undefined}
      whileTap={animate && isAvailable ? { scale: 0.98 } : undefined}
      transition={SPRING}
      onClick={isAvailable ? onSelect : undefined}
      disabled={!isAvailable}
      aria-pressed={isSelected}
      data-slot-cell
      aria-label={`${court.name}, de ${formatTime(slot.start)} à ${formatTime(slot.end)}, ${STATE_LABEL[slot.state]}${isAvailable ? `, ${formatTND(price)}, tarif ${peak ? 'de pointe' : 'heures creuses'}${slot.tag ? `, ${SLOT_TAG_LABEL[slot.tag].toLowerCase()}` : ''}` : ''}`}
      className={cn(
        'relative min-h-12 w-full rounded-lg border p-3 text-left transition-colors',
        'focus-visible:ring-3 focus-visible:ring-ring/50 focus-visible:outline-none',
        isAvailable &&
          !isSelected &&
          // Available = the success (Peacock Teal) tint; Lime Pulse stays for selection.
          'border-success/40 bg-success/5 hover:border-success cursor-pointer',
        // Selected: Lime Pulse fill — the one place green is a surface.
        isSelected && 'border-primary bg-primary text-primary-foreground',
        slot.state === 'occupied' &&
          'border-border bg-muted cursor-not-allowed opacity-60',
        slot.state === 'locked_buffer' &&
          'border-border bg-card cursor-not-allowed opacity-60',
        slot.state === 'past' &&
          'border-border/50 bg-transparent cursor-not-allowed opacity-60'
      )}
    >
      <div className="flex items-center justify-between gap-2">
        <span className="flex items-center gap-1.5 text-sm font-medium tabular-nums">
          <Clock className="size-3.5 opacity-70" aria-hidden />
          {formatTime(slot.start)}
        </span>

        <AnimatePresence initial={false}>
          {isSelected && (
            <motion.span
              key="check"
              initial={animate ? { scale: 0, rotate: -30 } : false}
              animate={{ scale: 1, rotate: 0 }}
              exit={animate ? { scale: 0, rotate: 30 } : undefined}
              transition={SPRING}
              className="flex size-5 items-center justify-center rounded-sm bg-primary-foreground/15"
            >
              <Check className="size-3.5" aria-hidden />
            </motion.span>
          )}
        </AnimatePresence>
      </div>

      <div className="mt-2 flex items-center justify-between gap-2">
        {isAvailable || isSelected ? (
          <span className="flex items-center gap-1.5">
            <span className="text-sm font-semibold tabular-nums">
              {formatTND(price)}
            </span>
            {peak && (
              <span
                className={cn(
                  'rounded-sm px-1 text-[0.65rem] font-medium uppercase tracking-wide',
                  isSelected ? 'bg-primary-foreground/15' : 'bg-accent text-accent-foreground'
                )}
              >
                Pointe
              </span>
            )}
          </span>
        ) : (
          <Badge
            variant={slot.state === 'locked_buffer' ? 'warning' : 'secondary'}
            className="text-[0.7rem]"
          >
            {slot.state === 'locked_buffer' && countdown
              ? `${STATE_LABEL[slot.state]} · ${countdown}`
              : STATE_LABEL[slot.state]}
          </Badge>
        )}

        <span
          className={cn(
            'text-xs tabular-nums',
            isSelected ? 'text-primary-foreground/70' : 'text-muted-foreground'
          )}
        >
          {formatTime(slot.end)}
        </span>
      </div>

      {slot.tag && (isAvailable || isSelected) && (
        <span
          data-slot-tag={slot.tag}
          className={cn(
            'mt-2 inline-flex items-center gap-1 rounded-sm px-1.5 py-0.5 text-[0.65rem] font-medium uppercase tracking-wide',
            isSelected
              ? 'bg-primary-foreground/15'
              : slot.tag === 'recommended'
                ? 'bg-primary/25 text-foreground'
                : slot.tag === 'high_demand'
                  ? 'bg-accent text-accent-foreground'
                  : 'bg-success/10 text-success'
          )}
        >
          {slot.tag === 'recommended' && <Sparkles className="size-3" aria-hidden />}
          {SLOT_TAG_LABEL[slot.tag]}
        </span>
      )}
    </motion.button>
  )

  return (
    <Tooltip>
      <TooltipTrigger asChild>
        {/* Disabled buttons swallow pointer events, so the trigger wraps them. */}
        <span className="block">{cell}</span>
      </TooltipTrigger>
      <TooltipContent>{tooltip}</TooltipContent>
    </Tooltip>
  )
}

/* ------------------------------ court column ----------------------------- */

function CourtColumn({
  court,
  selection,
  onSelect,
  animate,
  selectedDate,
}: {
  court: MatrixCourt
  selection: MatrixSelection | null
  onSelect: (court: MatrixCourt, slot: MatrixSlot) => void
  animate: boolean
  selectedDate: string
}) {
  const openCount = court.slots.filter((s) => s.state === 'available').length

  return (
    <Card className="h-full">
      <CardHeader>
        <CardTitle className="flex items-center justify-between gap-2 text-base">
          {court.name}
          <Badge variant={openCount > 0 ? 'success' : 'secondary'}>
            {openCount > 0 ? `${openCount} libre${openCount > 1 ? 's' : ''}` : 'Complet'}
          </Badge>
        </CardTitle>
        <ul aria-label="Détails du terrain" className="flex flex-wrap items-center gap-1.5 tabular-nums">
          <li>
            <Badge variant="outline" className="gap-1">
              <Clock aria-hidden />
              {slotMinutes(court.sport)} min
            </Badge>
          </li>
          <li>
            <Badge variant="secondary" title={`Prix d'un créneau de ${slotHoursLabel(slotMinutes(court.sport))}`}>
              {formatTND(slotFee(court.pricePerHour, slotMinutes(court.sport)))}
            </Badge>
          </li>
          {(court.nightSurchargePerHour ?? 0) > 0 && (
            <li>
              <Badge
                variant="outline"
                className="gap-1"
                title={`Supplément de nuit : +${formatTND(court.nightSurchargePerHour ?? 0)} pour les créneaux à partir de ${(court.nightStartsAt ?? '18:00:00').slice(0, 5)}`}
              >
                <Moon aria-hidden />
                +{formatTND(court.nightSurchargePerHour ?? 0)} · {(court.nightStartsAt ?? '18:00:00').slice(0, 5)}
              </Badge>
            </li>
          )}
        </ul>
      </CardHeader>

      <CardContent>
        {court.slots.length === 0 && (
          <p className="text-sm text-muted-foreground">
            Aucun créneau sur cette période.
          </p>
        )}
        <motion.div
          className="flex flex-col gap-2"
          initial={animate ? 'hidden' : false}
          animate="show"
          variants={{
            show: { transition: { staggerChildren: 0.04 } },
          }}
        >
          {court.slots.map((slot) => (
            <SlotCell
              key={`${court.id}-${slot.start}`}
              court={court}
              slot={slot}
              isSelected={
                selection?.courtId === court.id &&
                selection?.slot.start === slot.start
              }
              onSelect={() => onSelect(court, slot)}
              animate={animate}
              selectedDate={selectedDate}
            />
          ))}
        </motion.div>
      </CardContent>
    </Card>
  )
}

const noop = () => {}

/* --------------------------------- matrix -------------------------------- */

export function CourtSlotMatrix({
  courtData,
  selectedDate = venueDateString(),
  onSlotSelect,
  realtime,
  sport: controlledSport,
  onSportChange,
  hideSummaryOnMobile = false,
  className,
}: CourtSlotMatrixProps) {
  const reduceMotion = useReducedMotion()
  const animate = !reduceMotion

  // Mock data is memoised on the date so preview renders are stable.
  const courts = React.useMemo(
    () => courtData ?? buildMockCourts(selectedDate),
    [courtData, selectedDate]
  )

  const courtIds = React.useMemo(() => courts.map((c) => c.id), [courts])
  useRealtimeBookings(realtime?.orgId ?? '', selectedDate, realtime?.onChange ?? noop, {
    enabled: Boolean(realtime),
    courtIds,
  })

  const availableSports = React.useMemo(
    () => SPORTS.filter((s) => courts.some((c) => c.sport === s.value)),
    [courts]
  )

  const isControlled = controlledSport !== undefined
  const [internalSport, setInternalSport] = React.useState<Sport>(
    availableSports[0]?.value ?? 'padel'
  )
  const sport = controlledSport ?? internalSport
  const [selection, setSelection] = React.useState<MatrixSelection | null>(null)

  const sportCourts = React.useMemo(
    () => courts.filter((c) => c.sport === sport),
    [courts, sport]
  )

  // Mobile shows one court at a time; keep the active court valid on switch.
  const [mobileCourtId, setMobileCourtId] = React.useState<string | null>(null)
  const activeMobileCourt =
    sportCourts.find((c) => c.id === mobileCourtId) ?? sportCourts[0]

  // Not inside a setState updater: updaters run during render, and calling the
  // parent's callback from there updates the parent mid-render (a React error).
  const handleSelect = React.useCallback(
    (court: MatrixCourt, slot: MatrixSlot) => {
      const isSame = selection?.courtId === court.id && selection?.slot.start === slot.start
      const next: MatrixSelection | null = isSame
        ? null
        : {
            courtId: court.id,
            courtName: court.name,
            sport: court.sport,
            slot,
            price: slotPrice(court, slot, selectedDate),
            selectedDate,
          }
      setSelection(next)
      onSlotSelect?.(next)
    },
    [selection, onSlotSelect, selectedDate]
  )

  // Desktop keyboard: arrows / Home / End move focus between the free slots that are on screen.
  const handleGridKeyDown = (e: React.KeyboardEvent<HTMLElement>) => {
    const keys = ['ArrowDown', 'ArrowRight', 'ArrowUp', 'ArrowLeft', 'Home', 'End']
    if (!keys.includes(e.key)) return
    const target = e.target as HTMLElement
    if (!target.matches('[data-slot-cell]')) return
    const cells = Array.from(e.currentTarget.querySelectorAll<HTMLButtonElement>('[data-slot-cell]:not(:disabled)')).filter(
      (el) => el.offsetParent !== null
    )
    const at = cells.indexOf(target as HTMLButtonElement)
    if (at === -1) return
    const next =
      e.key === 'Home' ? 0 : e.key === 'End' ? cells.length - 1 : e.key === 'ArrowDown' || e.key === 'ArrowRight' ? Math.min(at + 1, cells.length - 1) : Math.max(at - 1, 0)
    e.preventDefault()
    cells[next]?.focus()
  }

  return (
    <TooltipProvider delayDuration={200}>
      <section className={cn('w-full', className)} aria-label="Court availability" onKeyDown={handleGridKeyDown}>
        <Tabs
          value={sport}
          onValueChange={(v) => {
            setInternalSport(v as Sport)
            onSportChange?.(v as Sport)
            setMobileCourtId(null)
          }}
        >
          {/* Controlled mode: the caller renders the tab bar instead. */}
          {!isControlled && (
          <TabsList variant="line" className="mb-4">
            {availableSports.map(({ value, label, icon: Icon }) => (
              <TabsTrigger key={value} value={value} className="relative max-md:min-h-12">
                {/* Shared layoutId slides the indicator between sports. */}
                {sport === value && animate && (
                  <motion.span
                    layoutId="activeSportTab"
                    transition={SPRING}
                    className="absolute inset-0 rounded-lg bg-card"
                  />
                )}
                <span className="relative z-10 flex items-center gap-1.5">
                  <Icon className="size-3.5" aria-hidden />
                  {label}
                </span>
              </TabsTrigger>
            ))}
          </TabsList>
          )}

          {availableSports.map(({ value }) => (
            <TabsContent key={value} value={value} className="mt-0">
              {sportCourts.length === 0 ? (
                <p className="text-sm text-muted-foreground">
                  Aucun terrain configuré pour ce sport.
                </p>
              ) : (
                <>
                  {/* Desktop: courts side by side. */}
                  <div
                    className="hidden gap-4 md:grid"
                    // Tablet (768-1024px) wraps to 2-3 courts per row, desktop fits more; empty tracks collapse.
                    style={{ gridTemplateColumns: 'repeat(auto-fit, minmax(13rem, 1fr))' }}
                  >
                    {sportCourts.map((court) => (
                      <CourtColumn
                        key={court.id}
                        court={court}
                        selection={selection}
                        onSelect={handleSelect}
                        animate={animate}
                        selectedDate={selectedDate}
                      />
                    ))}
                  </div>

                  {/* Mobile: one court at a time, chosen by a toggle group.
                      Not role="tab" — the sports above own the tab semantics,
                      and a second tab set confuses the accessibility tree. */}
                  <div className="md:hidden">
                    {sportCourts.length > 1 && (
                      <div
                        className="mb-3 flex flex-wrap gap-1.5"
                        role="group"
                        aria-label="Choisir un terrain"
                      >
                        {sportCourts.map((court) => (
                          <Button
                            key={court.id}
                            size="sm"
                            className="min-h-12 px-4 text-sm"
                            variant={
                              activeMobileCourt?.id === court.id
                                ? 'default'
                                : 'outline'
                            }
                            aria-pressed={activeMobileCourt?.id === court.id}
                            onClick={() => setMobileCourtId(court.id)}
                          >
                            {court.name}
                          </Button>
                        ))}
                      </div>
                    )}

                    {activeMobileCourt && (
                      <CourtColumn
                        court={activeMobileCourt}
                        selection={selection}
                        onSelect={handleSelect}
                        animate={animate}
                        selectedDate={selectedDate}
                      />
                    )}
                  </div>
                </>
              )}
            </TabsContent>
          ))}
        </Tabs>

        {/* Selection summary — the handoff point to the booking drawer. */}
        <AnimatePresence>
          {selection && (
            <motion.div
              initial={animate ? { opacity: 0, y: 8 } : false}
              animate={{ opacity: 1, y: 0 }}
              exit={animate ? { opacity: 0, y: 8 } : undefined}
              transition={SPRING}
              className={cn('mt-4 flex-wrap items-center justify-between gap-3 rounded-lg border border-border bg-card p-4', hideSummaryOnMobile ? 'hidden md:flex' : 'flex')}
              aria-live="polite"
            >
              <div className="text-sm">
                <p className="font-semibold">{selection.courtName}</p>
                <p className="text-muted-foreground tabular-nums">
                  {formatTime(selection.slot.start)}–{formatTime(selection.slot.end)}
                  {' · '}
                  {formatTND(selection.price)}
                </p>
              </div>
              <Button
                variant="ghost"
                size="sm"
                onClick={() => {
                  setSelection(null)
                  onSlotSelect?.(null)
                }}
              >
                Effacer
              </Button>
            </motion.div>
          )}
        </AnimatePresence>
      </section>
    </TooltipProvider>
  )
}

export default CourtSlotMatrix
