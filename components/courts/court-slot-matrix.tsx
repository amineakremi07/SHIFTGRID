/* ==========================================================================
   Public court availability matrix — Milestone 3.
   Desktop: one column per court, side by side. Mobile: courts become tabs.
   Visual language follows DESIGN.md — flat two-tone surfaces, Lime Pulse
   reserved for action/selection, separation via the canvas→card step.
   ========================================================================== */

export type { SlotState }
/** A bookable slot; generated by `lib/court-slots.ts`. */
/** A hint shown on a free slot: the player's habit, or how busy the club usually is then. Never a price change. */
export type SlotTag = 'recommended' | 'high_demand' | 'quiet'

export const SLOT_TAG_LABEL: Record<SlotTag, string> = {
  recommended: 'Recommandé pour vous',
  high_demand: 'Forte demande',
  quiet: 'Heure creuse',
}

export type MatrixSlot = CourtSlot & { tag?: SlotTag }

export interface MatrixCourt {
  id: string
  name: string
  sport: Sport
  /** Hourly rate in TND. Slot price is derived from the sport's duration. */
  pricePerHour: number
  /** Extra TND/hour for play at or after `nightStartsAt`. Omitted or 0 = none. */
  nightSurchargePerHour?: number
  /** Postgres TIME when lighting starts to be charged, e.g. "18:00:00". */
  nightStartsAt?: string
  slots: MatrixSlot[]
}

export interface MatrixSelection {
  courtId: string
  courtName: string
  sport: Sport
  slot: MatrixSlot
  /** Derived slot price in TND. */
  price: number
  selectedDate: string
}

export interface CourtSlotMatrixProps {
  /** Courts with their resolved slots. Defaults to mock data for preview. */
  courtData?: MatrixCourt[]
  /** YYYY-MM-DD. */
  selectedDate?: string
  /** Fires on select and on deselect (`null`). */
  onSlotSelect?: (selection: MatrixSelection | null) => void
  /**
   * Live updates. When given, the matrix listens for bookings and cancellations
   * at this club and calls `onChange` (typically a server refresh) so slots flip
   * between available and taken in every open tab. Omit for mock/preview data.
   */
  realtime?: { orgId: string; onChange: () => void }
  /**
   * Controlled sport. When provided, the matrix hides its own sport tabs and
   * follows this value — the caller owns the tab bar (e.g. the landing hero).
   */
  sport?: Sport
  /** Fires when the internal tabs change the sport (uncontrolled mode). */
  onSportChange?: (sport: Sport) => void
  /** The caller shows its own sticky action bar on phones, so skip the inline selection summary there. */
  hideSummaryOnMobile?: boolean
  className?: string
}

/* ----------------------------- sport metadata ---------------------------- */

const SPORTS: { value: Sport; label: string; icon: typeof Trophy }[] = [
  { value: 'padel', label: 'Padel', icon: Zap },
  { value: 'tennis', label: 'Tennis', icon: Trophy },
  { value: 'football', label: 'Football', icon: Calendar },
]

/** Tennis 60min; padel & football 90min. All carry a 15min buffer after play. */
function slotMinutes(sport: Sport) {
  return SPORT_DURATION_MIN[sport]
}

/**
 * Total for one slot, in TND, including any night lighting surcharge. Uses the
 * same `computePrice` the booking drawer and the server action use.
 */
function slotPrice(court: MatrixCourt, slot: MatrixSlot, dateStr: string) {
  return computePrice({
    pricePerHour: court.pricePerHour,
    nightSurchargePerHour: court.nightSurchargePerHour ?? 0,
    nightStartsAtMinutes: timeToMinutes(court.nightStartsAt ?? '18:00:00'),
    startMinutes: minutesSinceVenueDayStart(slot.start, dateStr),
    durationMinutes: slotMinutes(court.sport),
  }).total
}

/** Always venue (Tunis) time, never the visitor's browser timezone. */
const formatTime = formatVenueTime

/** TND, the platform currency — never EUR/USD. */
/**
 * Peak slots are the ones that carry the night-lighting surcharge, i.e. play at or
 * after the court's `nightStartsAt`. Off-peak slots are the base rate. A court
 * with no surcharge has no peak.
 */
export function slotIsPeak(court: MatrixCourt, slot: MatrixSlot, dateStr: string) {
  if ((court.nightSurchargePerHour ?? 0) <= 0) return false
  return (
    computePrice({
      pricePerHour: court.pricePerHour,
      nightSurchargePerHour: court.nightSurchargePerHour ?? 0,
      nightStartsAtMinutes: timeToMinutes(court.nightStartsAt ?? '18:00:00'),
      startMinutes: minutesSinceVenueDayStart(slot.start, dateStr),
      durationMinutes: slotMinutes(court.sport),
    }).surcharge > 0
  )
}

function formatTND(amount: number) {
  return `${amount.toFixed(amount % 1 === 0 ? 0 : 2)} TND`
}

/* ------------------------------- mock data ------------------------------- */

function buildMockSlots(
  sport: Sport,
  dateStr: string,
  pattern: SlotState[]
): MatrixSlot[] {
  const minutes = slotMinutes(sport)
  const step = minutes + BUFFER_MIN
  let cursor = 8 * 60 // courts open 08:00

  return pattern.map((state, i) => {
    const startMin = cursor
    cursor += step
    // Real instants in venue time, so preview data displays like production data.
    const toIso = (m: number) => venueInstant(dateStr, m).toISOString()

    return {
      start: toIso(startMin),
      end: toIso(startMin + minutes),
      state,
      bookingId: state === 'occupied' ? `mock-booking-${i}` : null,
      lockExpiresAt:
        state === 'locked_buffer'
          ? new Date(Date.now() + 4 * 60 * 1000).toISOString()
          : null,
    }
  })
}

